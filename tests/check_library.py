"""Exercise the duplicate rules against real files, because the fuzzy matcher is where a
wrong answer means either a skipped song or a re-download."""

import shutil
import subprocess

from pathlib import Path

from app import library
from app.sanitize import normalize_key, similar

TEMP_ROOT = Path(__file__).resolve().parent / ".work"
ROOT = TEMP_ROOT / "PENDRIVE"
ROOT.mkdir(parents=True, exist_ok=True)


def make_mp3(name: str, seconds: int) -> Path:
    target = ROOT / name
    target.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-y", "-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}",
         "-b:a", "192k", str(target)],
        capture_output=True, check=True,
    )
    return target


FILES = [
    ("Despacito - Luis Fonsi.mp3", 61),
    ("Arijit Singh - Tum Hi Ho.mp3", 42),
    ("Ed Sheeran - Perfect.mp3", 50),
    ("Lochaane-Urif-PopSong.mp3", 35),
]
for name, seconds in FILES:
    make_mp3(name, seconds)
# A playlist subfolder proves the index walks into folders.
make_mp3("Best Of 2019/Armaan Malik - Door.mp3", 44)

index = library.index_for(ROOT).build(force=True)
print(f"indexed {len(index.entries)} files")
for entry in index.entries:
    print("   ", entry["display"], "->", repr(entry["key"]))

CASES = [
    # (title, artist, duration, expect_duplicate, why)
    ("Despacito (Lyric Video)", "Luis Fonsi", 60, True, "one-word title, duration agrees"),
    ("Despacito", "Luis Fonsi", 300, False, "one-word title, duration is way off"),
    ("Tum Hi Ho", "Arijit Singh", 41, True, "different upload of the same song"),
    ("Tum Hi Ho (Karaoke Version)", "Arijit Singh", 41, True, "junk suffix stripped"),
    ("Tum Jao Kahin", "Arijit Singh", 41, False, "different song, same artist"),
    ("Perfect", "Ed Sheeran", 50, True, "title-only match"),
    ("Shape of You", "Ed Sheeran", 263, False, "different song, same artist"),
    ("Door", "Armaan Malik", 44, True, "found inside a playlist subfolder"),
    ("Hello World", "Some Band", 35, False, "single shared word is not enough"),
    ("Never Heard Of This", "Nobody", 99, False, "no match at all"),
]

print()
failures = 0
for title, artist, duration, expected, why in CASES:
    hit = index.find_duplicate(title, artist, duration)
    got = hit is not None
    ok = got == expected
    failures += 0 if ok else 1
    mark = "PASS" if ok else "FAIL"
    detail = f"matched {hit['display']} ({hit['score']:.2f})" if hit else "no match"
    print(f"{mark}  {title[:34]:35} {why:44} -> {detail}")

print()
print(f"{failures} failing case(s)")

# --------------------------------------------------------------- archive rules
archive = library.archive_path(ROOT, True)
archive.write_text(
    "# generated by Musica\nyoutube dQw4w9WgXcQ\nytdl https://vimeo.com/12345678\n",
    encoding="utf-8",
)
ids = library.read_archive_ids(archive)
print("archive ids:", sorted(ids))
assert library.in_archive(ids, "dQw4w9WgXcQ"), "YouTube ID must be found"
assert library.in_archive(ids, "DQw4w9WgXcQ"), "lookup is case-insensitive"
assert not library.in_archive(ids, "missingid"), "unknown ID must not match"

# ------------------------------------------------------------- key symmetry
a, b = normalize_key("Arijit Singh - Tum Hi Ho (Official Video)"), normalize_key("Tum Hi Ho", "Arijit Singh")
assert similar(a, b) >= 0.86, "the same song with two different titles must collide"
assert similar(normalize_key("Shape of You"), normalize_key("Perfect", "Ed Sheeran")) < 0.86

assert library.archive_path("/tmp/x", False).parent.name == "archives"
shutil.rmtree(ROOT, ignore_errors=True)
print("\nnaming, archive and duplicate rules all behave.")
